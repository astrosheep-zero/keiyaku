export type ContractCommand = keyof typeof CONTRACT_COMMAND_SPECS;

export function renderContractHelp(command: ContractCommand): string {
  const spec: ContractCommandSpec = CONTRACT_COMMAND_SPECS[command];
  if (command === "settings") {
    return [
      "Show effective Settings (read-only), merged from:",
      "  user      ~/.keiyaku/settings.json",
      "  project   <WorldRoot>/.keiyaku/settings.json",
      "A project record wholly shadows the same-name user record. Edit the files",
      "directly; there is no write command.",
      "",
      usageLine(spec.usage),
      "",
      "Recognized settings:",
      "  gates                            named gate groups for bind/amend --gates",
      "  worktree                         commands run when Contract worktrees are created or destroyed",
      "  git.requireBranchesToBeUpToDate  whether delivery and preview require an up-to-date target",
      "  providers                        Akuma providers and how each is run",
      "",
      "Akuma definitions are Markdown files, one per name:",
      "  user      ~/.keiyaku/akumas/<name>.md",
      "  project   <WorldRoot>/.keiyaku/akumas/<name>.md",
      "Project wins. Frontmatter: provider, base, model, effort, network,",
      "systemPromptMode, description. The body is an optional system prompt.",
      "Provider setup: see README Configuration.",
    ].join("\n");
  }
  const help = `${spec.purpose}\n\n${usageLine(spec.usage)}`;
  return spec.details === undefined ? help : `${help}\n\n${spec.details}`;
}
